#!/usr/bin/env python3
"""
Generate plugins/EclecticMistress/Presets.hpp from presets/eclecticmistress.json.

The presets (and the parameter defaults) live in the JSON file; this script
validates them against the declared ranges and emits the C++ table the DPF
wrapper exposes as programs. Those programs are then exported by DPF's TTL
generator to the LV2 presets.ttl and shown by VST3/CLAP hosts, so one data
file feeds every format.

The parameter order in the JSON must match the Parameters enum in
DistrhoPluginInfo.h. Program 0 must equal "defaults" (DPF convention:
program 0 is the plugin's initial state).

Usage: tools/gen_presets.py presets/eclecticmistress.json plugins/EclecticMistress/Presets.hpp
"""

import json
import os
import sys

EXPECTED = ["rate", "range", "color", "mix", "matrix"]


def fail(msg):
    sys.exit("gen_presets: " + msg)


def main():
    if len(sys.argv) != 3:
        fail("usage: gen_presets.py <presets.json> <out.hpp>")
    src, out = sys.argv[1], sys.argv[2]

    with open(src) as f:
        data = json.load(f)

    params = data.get("parameters")
    if params != EXPECTED:
        fail("parameters must be %s (the DistrhoPluginInfo.h enum order), got %s"
             % (EXPECTED, params))

    ranges = data.get("ranges", {})
    for k in EXPECTED:
        if k not in ranges or len(ranges[k]) != 2:
            fail("missing or malformed range for %r" % k)
        lo, hi = ranges[k]
        if not lo < hi:
            fail("range for %r must be lo < hi" % k)

    defaults = data.get("defaults", {})
    presets = data.get("presets", [])
    if not presets:
        fail("no presets")

    def values(entry, where):
        v = entry.get("values", {})
        out = []
        for k in EXPECTED:
            if k not in v:
                fail("%s: missing %r" % (where, k))
            x = float(v[k])
            lo, hi = ranges[k]
            if not (lo <= x <= hi):
                fail("%s: %s=%g outside [%g, %g]" % (where, k, x, lo, hi))
            if k == "matrix" and x not in (0.0, 1.0):
                fail("%s: matrix must be 0 or 1" % where)
            out.append(x)
        return out

    dv = values({"values": defaults}, "defaults")
    entries = []
    for i, p in enumerate(presets):
        name = p.get("name", "").strip()
        if not name:
            fail("preset %d has no name" % i)
        entries.append((name, values(p, "preset %d (%s)" % (i, name))))

    # DPF program 0 is the initial state: require it to be the defaults.
    if any(abs(a - b) > 1e-6 for a, b in zip(dv, entries[0][1])):
        fail("program 0 must equal defaults (edit the first preset or defaults)")

    def f(x):
        # stable, readable float literal (always with a decimal point)
        s = ("%.6f" % x).rstrip("0").rstrip(".")
        if s in ("", "-0"):
            s = "0"
        if "." not in s:
            s += ".0"
        return s + "f"

    def row(name, vals):
        return '    { "%s", { %s } },' % (name.replace('"', '\\"'),
                                          ", ".join(f(x) for x in vals))

    lines = [
        "/*",
        " * Eclectic Mistress - preset table and parameter defaults.",
        " *",
        " * GENERATED by tools/gen_presets.py from %s -- do not edit by hand." % src,
        " * Edit the JSON (presets/eclecticmistress.json) and run `make presets`.",
        " *",
        " * Copyright (C) 2026 Dataforte",
        " * SPDX-License-Identifier: GPL-2.0-or-later",
        " */",
        "",
        "#pragma once",
        "",
        "namespace em_presets {",
        "",
        "struct Entry {",
        "    const char* name;",
        "    float value[5];   // in the kParamRate..kParamMatrix order",
        "};",
        "",
        "constexpr Entry kDefaults = " + row("Default", dv).strip().rstrip(",") + ";",
        "",
        "constexpr Entry kEntries[] = {",
    ]
    for name, vals in entries:
        lines.append(row(name, vals))
    lines += [
        "};",
        "constexpr unsigned kCount = sizeof(kEntries) / sizeof(kEntries[0]);",
        "",
        "} // namespace em_presets",
        "",
    ]

    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    print("wrote %s (%d presets)" % (out, len(entries)))


if __name__ == "__main__":
    main()
